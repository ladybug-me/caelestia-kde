#!/usr/bin/env python3
"""Generate the search index for every setting row a Nexus page renders.

`PageDictionary.qml` names a page, a section or a setting by hand, and search
can only find what that table names: rows like "Bezel mode" or "Subcategory
side pane" are rendered by the page but are invisible to a query. This script
walks the page sources and writes `PageRowIndex.qml`, which `PageRegistry`
merges into the search index, so every row is searchable and landing on one
selects it.

The output is committed: the shell, the translation catalogues and the CI
checks all read it without running a build. `--check` regenerates in memory
and fails when the committed file no longer matches the pages.

    python3 tools/generate_settings_index.py           # rewrite the file
    python3 tools/generate_settings_index.py --check    # verify, do not write
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NEXUS = ROOT / "shell" / "modules" / "nexus"
PAGES = NEXUS / "pages"
REGISTRY = NEXUS / "PageCompRegistry.qml"
OUTPUT = NEXUS / "PageRowIndex.qml"

# Components that render a single setting or a menu entry. Each one is a row a
# query should be able to find, so its label is what the user will type.
ROW_COMPONENTS = (
    "ToggleRow",
    "StepperRow",
    "DoubleStepperRow",
    "SelectRow",
    "TextFieldRow",
    "NavRow",
    "SliderRow",
)

# How far below the component opening the label is allowed to be. Rows declare
# `reset`, `Layout.*` and other properties before the label, so a couple of
# lines is not enough.
LOOKAHEAD = 12

PAGE_BLOCK = re.compile(r"^ {8}Component \{$")
SUBPAGE = re.compile(r"SubPage \{\s*slot: (\d+);.*?Component \{ (\w+) \{\}", re.S)
LABEL = re.compile(r'(?:label|text): qsTr\("([^"]*)"\)')
SUBTEXT = re.compile(r'subtext: qsTr\("([^"]*)"\)')
TITLE = re.compile(r'^ {4}title: qsTr\("([^"]*)"\)', re.M)

HEADER = """\
// Generated by tools/generate_settings_index.py - do not edit by hand.
// Every setting row the Nexus pages render, with the page and sub-page slot it
// lives in, so the search bar can find a row that PageDictionary does not name.
"""


def component_slots() -> dict[str, list[tuple[int, int]]]:
    """Map a page component name to every (pageIdx, subPageIdx) that renders it."""
    slots: dict[str, list[tuple[int, int]]] = {}
    page = -1
    for line in REGISTRY.read_text(encoding="utf-8").splitlines():
        if PAGE_BLOCK.match(line):
            page += 1
            continue
        match = SUBPAGE.search(line)
        if match and page >= 0:
            slots.setdefault(match.group(2), []).append((page, int(match.group(1))))
    return slots


def page_files() -> dict[str, Path]:
    return {path.stem: path for path in sorted(PAGES.rglob("*.qml"))}


def context_files() -> set[str]:
    """Page components that describe an object picked earlier, not a place to open.

    Such a page cannot state its own title in the source; opening it from a
    query would land on an empty page, so its rows stay out of the index.
    """
    return {name for name, path in page_files().items() if not TITLE.search(path.read_text(encoding="utf-8"))}


def context_slots() -> set[tuple[int, int]]:
    slots = component_slots()
    excluded = context_files()
    return {
        (page, slot)
        for name, targets in slots.items()
        for page, slot in targets
        if name in excluded
    }


def rows_in(path: Path) -> list[tuple[str, str]]:
    """The (label, subtext) of every row the file renders, in source order."""
    lines = path.read_text(encoding="utf-8").splitlines()
    found: list[tuple[str, str]] = []
    for number, line in enumerate(lines):
        if not any(re.match(rf"^ *{name} \{{", line) for name in ROW_COMPONENTS):
            continue
        label = ""
        subtext = ""
        for offset in range(1, LOOKAHEAD + 1):
            if number + offset >= len(lines):
                break
            candidate = lines[number + offset]
            if not label:
                match = LABEL.search(candidate)
                if match:
                    label = match.group(1)
                    continue
            if not subtext:
                match = SUBTEXT.search(candidate)
                if match:
                    subtext = match.group(1)
            if label and subtext:
                break
        if label:
            found.append((label, subtext))
    return found


def collect_rows() -> list[dict[str, object]]:
    """Every searchable row, deduplicated on (label, page, slot)."""
    slots = component_slots()
    files = page_files()

    missing = sorted(name for name in slots if name not in files)
    if missing:
        raise SystemExit(
            "PageCompRegistry names components with no page file: " + ", ".join(missing)
        )

    rows: list[dict[str, object]] = []
    seen: set[tuple[str, int, int]] = set()
    excluded = context_files()
    for name in sorted(files):
        targets = slots.get(name)
        if not targets or name in excluded:
            continue
        title_match = TITLE.search(files[name].read_text(encoding="utf-8"))
        if not title_match:
            continue
        title = title_match.group(1)
        for label, subtext in rows_in(files[name]):
            for page, slot in targets:
                key = (label, page, slot)
                if key in seen:
                    continue
                seen.add(key)
                rows.append(
                    {
                        "label": label,
                        "description": subtext,
                        "section": title,
                        "pageIdx": page,
                        "subPageIdx": slot,
                    }
                )
    return rows


def quote(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def render(rows: list[dict[str, object]]) -> str:
    out = [HEADER, "pragma Singleton", "", "import QtQuick", "", "QtObject {", "    readonly property list<var> rows: ["]
    for row in rows:
        parts = [f'label: qsTr("{quote(str(row["label"]))}")']
        if row["description"]:
            parts.append(f'description: qsTr("{quote(str(row["description"]))}")')
        if row["section"]:
            parts.append(f'section: qsTr("{quote(str(row["section"]))}")')
        parts.append(f'pageIdx: {row["pageIdx"]}')
        parts.append(f'subPageIdx: {row["subPageIdx"]}')
        out.append("        {\n            " + ",\n            ".join(parts) + "\n        },")
    out.append("    ]")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed index differs from what the pages render",
    )
    args = parser.parse_args()

    rendered = render(collect_rows())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run tools/generate_settings_index.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    with OUTPUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({rendered.count('label:')} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
