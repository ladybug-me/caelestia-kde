// Turns the shell's scheme files into the two things the site needs:
//
//   src/styles/generated/palettes.css   one rule per palette and mode, so
//                                       switching palettes is a CSS attribute
//                                       change with no JavaScript and no data
//                                       payload
//   src/data/palettes.json              the tiny index the picker renders from
//
// Both are generated at build time (npm run generate, wired into predev and
// prebuild) and are not committed.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE_ROLES, TERM_ROLES, missingRoles, readSchemes } from './lib/schemes.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const cssPath = join(here, '..', 'src', 'styles', 'generated', 'palettes.css');
const jsonPath = join(here, '..', 'src', 'data', 'palettes.json');

const HEADER = `/* Generated by scripts/gen-palettes.mjs from src/schemes - do not edit. */

/* The shell paints code blocks from the palette's own terminal colours, so the
   site does too. Astro renders code through Shiki's css-variables theme, which
   reads these names. */
`;

// Shiki token names -> the role they are painted from. Anything not listed uses
// the block's foreground colour.
const SHIKI_TOKENS = {
    constant: 'term6',
    string: 'term2',
    'string-expression': 'term2',
    comment: 'overlay0',
    keyword: 'term5',
    parameter: 'term3',
    function: 'term4',
    punctuation: 'subtext1',
    link: 'term4',
};

function paletteRule(selector, roles) {
    const lines = [`${selector} {`];

    for (const [role, property] of Object.entries(SITE_ROLES)) {
        if (roles[role]) lines.push(`    ${property}: ${roles[role]};`);
    }
    for (const [index, role] of TERM_ROLES.entries()) {
        if (roles[role]) lines.push(`    --term-${index}: ${roles[role]};`);
    }

    if (roles.text && roles.surfaceContainerLowest) {
        lines.push('');
        lines.push('    --astro-code-foreground: var(--code-text);');
        lines.push('    --astro-code-background: var(--surface-lowest);');
    }
    for (const [token, role] of Object.entries(SHIKI_TOKENS)) {
        if (!roles[role]) continue;
        lines.push(`    --astro-code-token-${token}: var(--term-${TERM_ROLES.indexOf(role)});`);
    }

    lines.push('}');
    return lines.join('\n');
}

/**
 * The colours the picker grid shows before a palette is chosen.
 *
 * The values are written out rather than referencing the palette's custom
 * properties: a `var(--primary)` inside the swatch would resolve against the
 * *current* palette, because that is what is on the cascade at that element, and
 * every swatch in the grid would show the same colour.
 */
function swatchRule(selector, roles) {
    const picks = ['background', 'primary', 'tertiary', 'surfaceContainerHigh'];

    const lines = picks
        .filter((role) => roles[role])
        .map((role) => `    --swatch-${SITE_ROLES[role].replace(/^--/, '')}: ${roles[role]};`);

    return lines.length === 0 ? '' : `${selector} {\n${lines.join('\n')}\n}`;
}

function command(name, flavour, mode) {
    return `caelestia scheme set -n ${name} -f ${flavour} -m ${mode}`;
}

/**
 * Builds both artefacts in memory. Exported so the unit tests can assert on the
 * generated CSS without writing files or depending on a previous build step.
 */
export function buildPalettes({ schemesDir = join(repoRoot, 'src', 'schemes') } = {}) {
    const { brand, others } = readSchemes(schemesDir);

    const blocks = [HEADER];
    const index = [];
    const warnings = [];

    // Brand defaults on :root, so a role a palette does not carry still resolves
    // to something (the vendored palettes predate `success`, and a
    // wallpaper-derived palette is written inline). Palette rules come later in
    // the file and win on equal specificity.
    for (const [mode, roles] of Object.entries(brand.flavours[0].modes)) {
        blocks.push(paletteRule(mode === 'dark' ? ':root' : `:root[data-mode='${mode}']`, roles));
    }

    for (const scheme of [brand, ...others]) {
        for (const flavour of scheme.flavours) {
            const missing = new Set();
            for (const [mode, roles] of Object.entries(flavour.modes)) {
                for (const role of missingRoles(roles)) missing.add(role);
                blocks.push(paletteRule(`[data-palette='${scheme.id}-${flavour.id}'][data-mode='${mode}']`, roles));
            }

            // A flavour with one mode shows the same swatch colours in both.
            const dark = flavour.modes.dark ?? flavour.modes.light;
            const light = flavour.modes.light ?? flavour.modes.dark;
            blocks.push(swatchRule(`:root[data-mode='dark'] .swatch[data-palette='${scheme.id}-${flavour.id}']`, dark));
            blocks.push(
                swatchRule(`:root[data-mode='light'] .swatch[data-palette='${scheme.id}-${flavour.id}']`, light),
            );

            const modes = Object.keys(flavour.modes);
            index.push({
                id: `${scheme.id}-${flavour.id}`,
                name: scheme.id,
                flavour: flavour.id,
                label: scheme.label,
                flavourLabel: flavour.label,
                modes,
                commands: Object.fromEntries(modes.map((mode) => [mode, command(scheme.id, flavour.id, mode)])),
                brand: scheme.id === brand.id,
            });

            if (missing.size > 0) {
                warnings.push(`${scheme.id}/${flavour.id}: ${[...missing].join(', ')}`);
            }
        }
    }

    const brandEntry = index.find((entry) => entry.brand && entry.modes.includes('dark'));
    const brandRoles = brand.flavours.find((flavour) => flavour.id === brandEntry.flavour).modes.dark;
    const brandMissing = missingRoles(brandRoles);
    if (brandMissing.length > 0) {
        throw new Error(
            `The brand palette is missing roles the site needs: ${brandMissing.join(', ')}. ` +
                'Either src/schemes/caelestia changed shape or SITE_ROLES is out of step.',
        );
    }

    return {
        css: `${blocks.filter(Boolean).join('\n\n')}\n`,
        index: { default: { palette: brandEntry.id, mode: 'dark' }, palettes: index },
        warnings,
        roleCount: Object.keys(brandRoles).length,
    };
}

function main() {
    const { css, index, warnings, roleCount } = buildPalettes();

    mkdirSync(dirname(cssPath), { recursive: true });
    writeFileSync(cssPath, css, 'utf8');

    mkdirSync(dirname(jsonPath), { recursive: true });
    writeFileSync(jsonPath, `${JSON.stringify(index, null, 4)}\n`, 'utf8');

    console.log(
        `palettes: ${index.palettes.length} palettes across ` +
            `${new Set(index.palettes.map((entry) => entry.name)).size} names ` +
            `(${roleCount} roles each), ${Object.keys(SITE_ROLES).length} exposed, css + index written`,
    );
    if (warnings.length > 0) {
        // Not fatal: a role a palette does not carry keeps the brand's value.
        console.warn(`palettes: these inherit the brand colour for the roles listed:\n  ${warnings.join('\n  ')}`);
    }
}

// Only when run as a script; importing this module for its exports must not
// write anything.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main();
}
