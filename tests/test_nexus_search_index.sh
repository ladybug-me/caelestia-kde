#!/usr/bin/env bash
# suite: fast

set -uo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/helpers.sh"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NEXUS="$REPO_ROOT/shell/modules/nexus"
INDEX="$NEXUS/PageRowIndex.qml"
REGISTRY="$NEXUS/PageRegistry.qml"
RESULTS="$NEXUS/navpane/SearchResults.qml"

test_the_index_is_committed_and_says_it_is_generated() {
    assert_file_contains "$INDEX" "Generated by tools/generate_settings_index.py" \
        "the index should say where it came from"
    assert_file_contains "$INDEX" "pragma Singleton" \
        "the index is a singleton the registry can import"
}

test_the_index_matches_the_pages_it_is_generated_from() {
    if ! command -v python3 >/dev/null 2>&1; then
        skip_test "python3 is not installed"
        return 0
    fi

    local output
    if ! output="$(cd "$REPO_ROOT" && python3 tools/generate_settings_index.py --check 2>&1)"; then
        fail "the committed index is out of date: $output"
    fi
}

test_the_registry_searches_the_generated_rows() {
    assert_file_contains "$REGISTRY" "PageRowIndex.rows.forEach" \
        "search should index the rows the pages render, not only the dictionary"
    assert_file_contains "$REGISTRY" "sectionLabel: row.section || \"\"" \
        "a generated result should carry the section it came from"
}

test_a_row_the_dictionary_already_names_is_not_indexed_twice() {
    assert_file_contains "$REGISTRY" "named[\`\${entry.pageIdx}|\${entry.subPageIdx}|\${entry.settingLabel.toLowerCase()}\`]" \
        "curated entries should win over the generated copy"
}

test_a_result_shows_where_in_the_page_it_lands() {
    assert_file_contains "$RESULTS" "readonly property string sectionLabel: modelData.sectionLabel ?? \"\"" \
        "results should read the section of a generated row"
    assert_file_contains "$RESULTS" 'qsTr("in %1 › %2").arg(item.pageLabel).arg(item.sectionLabel)' \
        "a row result should name its page and section"
}

test_a_row_that_needs_a_picked_object_is_not_a_destination() {
    assert_file_not_contains "$INDEX" "Reconnect on startup" \
        "a page that only describes the chosen device cannot be opened from a query"
    assert_file_contains "$REPO_ROOT/tools/generate_settings_index.py" "def context_files()" \
        "the generator should decide that from the pages, not a hand-kept list"
}

run_tests
